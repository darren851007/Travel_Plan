/* 「CI 160」「ci160」→「CI」；不在清單裡回傳空字串 */
Trip.airlineCode = function (flightNumber) {
  const match = String(flightNumber || "").trim().toUpperCase().match(/^([A-Z0-9]{2})\s*\d/);
  return match && Trip.airlines[match[1]] ? match[1] : "";
};
